# Helper for linear interpolation between waypoints
def interpolate_waypoints(anchor_pts, count):
    coords = []
    for i in range(count):
        for seg in range(len(anchor_pts) - 1):
            s0, x0, y0 = anchor_pts[seg]
            s1, x1, y1 = anchor_pts[seg+1]
            if s0 <= i <= s1:
                t = (i - s0) / (s1 - s0) if s1 > s0 else 0.0
                cx = x0 + t * (x1 - x0)
                cy = y0 + t * (y1 - y0)
                coords.append((round(cx, 2), round(cy, 2)))
                break
    return coords

