def format_node(step, name, muni, node_type, x, y, desc, road):
    step_str = f"{step:04d}"
    return f"""        SugorokuNode(
            id = "node_{step_str}",
            stepIndex = {step},
            name = "{name}",
            municipality = "{muni}",
            type = SugorokuNodeType.{node_type},
            x = {x:.2f}f,
            y = {y:.2f}f,
            description = "{desc}",
            roadName = "{road}",
        ),"""

def main():
    with open(ROUTE_FILE, 'r', encoding='utf-8') as f:
        content = f.read()

    # Extract existing x, y for each step
    xy_map = {}
    pattern = re.compile(r'stepIndex\s*=\s*(\d+),.*?x\s*=\s*([0-9.]+)f,\s*y\s*=\s*([0-9.]+)f,', re.DOTALL)
    for m in pattern.finditer(content):
        s = int(m.group(1))
        x = float(m.group(2))
        y = float(m.group(3))
        xy_map[s] = (x, y)

    # 1. Replace Tomamae nodes (846 .. 885)
    tomamae_block_parts = []
    for step, name, muni, ntype, desc, road in TOMAMAE_NODES:
        x, y = xy_map[step]
        tomamae_block_parts.append(format_node(step, name, muni, ntype, x, y, desc, road))
    new_tomamae_block = "\n".join(tomamae_block_parts)

    # 2. Replace Wakkanai nodes (1130 .. 1175)
    wakkanai_block_parts = []
    for step, name, muni, ntype, desc, road in WAKKANAI_NODES:
        x, y = xy_map[step]
        wakkanai_block_parts.append(format_node(step, name, muni, ntype, x, y, desc, road))
    new_wakkanai_block = "\n".join(wakkanai_block_parts)

    # Find boundaries using regex
    tomamae_re = re.compile(
        r'(\s*SugorokuNode\(\s*id\s*=\s*\"node_0846\".*?stepIndex\s*=\s*885,.*?\),)',
        re.DOTALL
    )
    wakkanai_re = re.compile(
        r'(\s*SugorokuNode\(\s*id\s*=\s*\"node_1130\".*?stepIndex\s*=\s*1175,.*?\),)',
        re.DOTALL
    )

    m_tomamae = tomamae_re.search(content)
    if not m_tomamae:
        print("Error: Could not locate Tomamae block in file!")
        return

    content = content[:m_tomamae.start()] + "\n" + new_tomamae_block + content[m_tomamae.end():]

    m_wakkanai = wakkanai_re.search(content)
    if not m_wakkanai:
        print("Error: Could not locate Wakkanai block in file!")
        return

    content = content[:m_wakkanai.start()] + "\n" + new_wakkanai_block + content[m_wakkanai.end():]

    with open(ROUTE_FILE, 'w', encoding='utf-8') as f:
        f.write(content)

    print("Successfully refined Tomamae side-trip and Wakkanai south-to-north route in HokkaidoAct1Route.kt!")

if __name__ == '__main__':
    main()
