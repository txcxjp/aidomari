    if n == 1:
        return [chain[0]]
    cum_d = [0.0]
    for i in range(len(chain) - 1):
        cum_d.append(cum_d[-1] + math.hypot(chain[i+1][0] - chain[i][0], chain[i+1][1] - chain[i][1]))
    total = cum_d[-1]
    res = []
    for i in range(n):
        t_d = i * total / (n - 1)
        idx = bisect.bisect_left(cum_d, t_d)
        if idx == 0:
            pt = chain[0]
        elif idx >= len(chain):
            pt = chain[-1]
        else:
            d0, d1 = cum_d[idx-1], cum_d[idx]
            p0, p1 = chain[idx-1], chain[idx]
            t = (t_d - d0) / (d1 - d0) if d1 > d0 else 0
            pt = (round(p0[0] + t * (p1[0] - p0[0]), 2), round(p0[1] + t * (p1[1] - p0[1]), 2))
        res.append(pt)
    return res

